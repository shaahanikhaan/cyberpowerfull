"""Native HTTP probe: send one bounded, scope-checked request and read the evidence.

This is the delivery primitive for generated payloads. It never follows a
redirect off the target host, never sends more than one follow-up request, and
records exactly what came back (status, headers, marker reflection, redirects).
"""

from __future__ import annotations

import hashlib
import http.client
import json
import re
import ssl
import time
from typing import Any, ClassVar, Literal
from urllib.parse import urlparse

from pydantic import Field, field_validator

from cyberpowerfull.models import Finding, Phase, Severity
from cyberpowerfull.tools.base import BaseTool, ToolStatus, UrlInput, _Exec, truncate

_ALLOWED_METHODS = ("GET", "POST", "PUT", "PATCH", "OPTIONS")
_REDIRECT_CODES = {301, 302, 303, 307, 308}
_SQL_ERROR_PATTERNS = (
    "you have an error in your sql syntax",
    "unclosed quotation mark",
    "ora-0",
    "pg_query",
    "postgresql",
    "sqlstate",
    "mysql_fetch",
    "sqlite error",
    "quoted string not properly terminated",
)
_BANNER_RE = re.compile(r"^(?P<product>[A-Za-z][\w.\-]*)(?:/(?P<version>[\w.\-]+))?")


class HttpProbeArgs(UrlInput):
    """Validated native HTTP request arguments."""

    method: Literal["GET", "POST", "PUT", "PATCH", "OPTIONS"] = "GET"
    path: str | None = Field(default=None, max_length=1024)
    headers: dict[str, str] = Field(default_factory=dict)
    body: str | None = Field(default=None, max_length=8192)
    marker: str | None = Field(default=None, max_length=64)
    timeout_s: float = Field(default=10.0, ge=0.5, le=30.0)
    capture_bytes: int = Field(default=65536, ge=1024, le=262144)
    follow_redirects: bool = True

    @field_validator("path")
    @classmethod
    def _check_path(cls, value: str | None) -> str | None:
        if value is None:
            return None
        if not value.startswith("/"):
            raise ValueError("path must start with '/'")
        if any(ord(char) < 0x20 for char in value):
            raise ValueError("path must not contain control characters")
        return value

    @field_validator("headers")
    @classmethod
    def _check_headers(cls, value: dict[str, str]) -> dict[str, str]:
        if len(value) > 10:
            raise ValueError("at most 10 custom headers are allowed")
        for name, header_value in value.items():
            if not re.fullmatch(r"[A-Za-z0-9\-]{1,64}", name):
                raise ValueError(f"invalid header name: {name!r}")
            if "\r" in header_value or "\n" in header_value:
                raise ValueError(f"header {name!r} must not contain CR/LF")
            if len(header_value) > 2048:
                raise ValueError(f"header {name!r} is too long")
        return value


class HttpProbeTool(BaseTool):
    name = "http_probe"
    phase = Phase.VALIDATION
    skill = "api_security"
    binary: ClassVar[str | None] = None
    timeout_s = 45
    description = (
        "Send one bounded HTTP request (GET/POST/PUT/PATCH/OPTIONS) inside scope and report "
        "status, headers, redirect target, SQL error signatures, and whether your marker was "
        "reflected. Use it to deliver payloads generated by the payload tool."
    )
    input_model = HttpProbeArgs

    def build_argv(self, args: HttpProbeArgs, out_file: str | None = None) -> list[str]:
        argv = ["http_probe", "--method", args.method, "--url", self._url(args)]
        for name, value in args.headers.items():
            argv.extend(["--header", f"{name}: {value}"])
        if args.body:
            argv.extend(["--body", args.body])
        return argv

    @staticmethod
    def _url(args: HttpProbeArgs) -> str:
        if not args.path:
            return args.target
        parsed = urlparse(args.target)
        return f"{parsed.scheme}://{parsed.netloc}{args.path}"

    # -- execution ---------------------------------------------------------
    def _execute(self, args: HttpProbeArgs, argv: list[str], policy: Any) -> _Exec:
        url = self._url(args)
        try:
            result = probe_http(
                url,
                method=args.method,
                headers=args.headers,
                body=args.body,
                marker=args.marker,
                timeout=args.timeout_s,
                capture_bytes=args.capture_bytes,
                follow_redirects=args.follow_redirects,
            )
        except Exception as exc:
            return _Exec(status=ToolStatus.ERROR, error=f"{exc.__class__.__name__}: {exc}")
        if result.get("error"):
            return _Exec(
                stdout=json.dumps(result),
                status=ToolStatus.ERROR,
                error=str(result["error"]),
            )
        return _Exec(stdout=json.dumps(result))

    # -- parsing -----------------------------------------------------------
    def parse(self, args: HttpProbeArgs, output: str, out_file: str | None = None) -> list[Finding]:
        if not output.strip():
            return []
        try:
            payload = json.loads(output)
        except json.JSONDecodeError:
            return []
        if payload.get("error"):
            return []
        findings: list[Finding] = []
        url = str(payload.get("url") or self._url(args))
        status = payload.get("status")
        headers = {str(k).lower(): v for k, v in (payload.get("headers") or {}).items()}
        excerpt = str(payload.get("body_excerpt") or "")
        lowered = excerpt.lower()

        if payload.get("marker_reflected"):
            findings.append(
                self.finding(
                    title="Marker reflected in response body",
                    severity=Severity.MEDIUM,
                    confidence=0.6,
                    target=args.target,
                    endpoint=url,
                    evidence=truncate(
                        f"status={status} marker={args.marker} appears unencoded in the body"
                    ),
                    skill="xss",
                    remediation="Encode or reject user input on output and apply a strict CSP.",
                )
            )

        redirect = payload.get("redirect") or {}
        if redirect.get("external"):
            findings.append(
                self.finding(
                    title=f"Open redirect to external host: {redirect.get('host')}",
                    severity=Severity.MEDIUM,
                    confidence=0.8,
                    target=args.target,
                    endpoint=url,
                    evidence=truncate(f"status={status} Location={redirect.get('location')}"),
                    skill="open_redirect",
                    verified=True,
                    remediation="Validate redirect targets against an allowlist of local paths.",
                )
            )

        if any(pattern in lowered for pattern in _SQL_ERROR_PATTERNS):
            findings.append(
                self.finding(
                    title="Verbose database error returned to the client",
                    severity=Severity.MEDIUM,
                    confidence=0.7,
                    target=args.target,
                    endpoint=url,
                    evidence=truncate(f"status={status} body contains a DB error signature"),
                    skill="sql_injection",
                    verified=True,
                    remediation="Return generic errors and log details server-side only.",
                )
            )

        allowed = headers.get("allow")
        if allowed:
            findings.append(
                self.finding(
                    title=f"HTTP methods advertised: {allowed}",
                    severity=Severity.INFO,
                    confidence=0.8,
                    target=args.target,
                    endpoint=url,
                    evidence=truncate(f"Allow: {allowed} status={status}"),
                    skill="api_security",
                    verified=True,
                )
            )

        if isinstance(status, int) and status >= 500:
            findings.append(
                self.finding(
                    title=f"Server error {status} on probe request",
                    severity=Severity.INFO,
                    confidence=0.7,
                    target=args.target,
                    endpoint=url,
                    evidence=truncate(f"status={status} len={payload.get('body_length')}"),
                    skill="information_disclosure",
                    verified=True,
                )
            )
        return findings

    def observations(self, args: HttpProbeArgs, output: str) -> list[str]:
        try:
            payload = json.loads(output)
        except json.JSONDecodeError:
            return ["http_probe produced unparsable output"]
        if payload.get("error"):
            return [f"http_probe: {payload['error']}"]
        server = (payload.get("headers") or {}).get("server")
        return [
            f"http_probe {payload.get('method')} {payload.get('url')} -> "
            f"status={payload.get('status')} len={payload.get('body_length')} "
            f"marker_reflected={payload.get('marker_reflected')} "
            f"server={server} elapsed_ms={payload.get('elapsed_ms')}"
        ]


def _header_pairs(message: http.client.HTTPMessage) -> dict[str, str]:
    pairs: dict[str, str] = {}
    for name, value in message.items():
        key = name.lower()
        if key == "set-cookie":
            pairs[key] = " | ".join(part for part in (pairs.get(key), value) if part)
        else:
            # A later value is the application's own header (e.g. Server), which is
            # more informative than the framework default.
            pairs[key] = value
    return pairs


def _request_once(
    url: str,
    *,
    method: str,
    headers: dict[str, str],
    body: str | None,
    timeout: float,
    capture_bytes: int,
) -> dict[str, Any]:
    parsed = urlparse(url)
    host = parsed.hostname or ""
    port = parsed.port
    path = parsed.path or "/"
    if parsed.query:
        path = f"{path}?{parsed.query}"
    connection: http.client.HTTPConnection
    if parsed.scheme == "https":
        connection = http.client.HTTPSConnection(
            host, port or 443, timeout=timeout, context=ssl.create_default_context()
        )
    else:
        connection = http.client.HTTPConnection(host, port or 80, timeout=timeout)
    started = time.perf_counter()
    try:
        request_headers = {"User-Agent": "cyberpowerfull (authorised-test)", **headers}
        connection.request(method, path, body=body, headers=request_headers)
        response = connection.getresponse()
        raw = response.read(capture_bytes)
        elapsed = int((time.perf_counter() - started) * 1000)
        response_headers = _header_pairs(response.headers)
        return {
            "url": url,
            "method": method,
            "status": response.status,
            "reason": response.reason,
            "headers": response_headers,
            "location": response_headers.get("location"),
            "content_type": response_headers.get("content-type"),
            "body_length": len(raw),
            "body_sha256": hashlib.sha256(raw).hexdigest()[:16],
            "body_excerpt": raw[:2048].decode("utf-8", errors="replace"),
            "elapsed_ms": elapsed,
        }
    finally:
        connection.close()


def probe_http(
    url: str,
    *,
    method: str = "GET",
    headers: dict[str, str] | None = None,
    body: str | None = None,
    marker: str | None = None,
    timeout: float = 10.0,
    capture_bytes: int = 65536,
    follow_redirects: bool = True,
) -> dict[str, Any]:
    """Send one request (plus at most one same-host redirect) and describe the result."""
    headers = dict(headers or {})
    result: dict[str, Any]
    try:
        result = _request_once(
            url,
            method=method,
            headers=headers,
            body=body,
            timeout=timeout,
            capture_bytes=capture_bytes,
        )
    except (OSError, http.client.HTTPException, ValueError) as exc:
        return {"url": url, "error": f"{exc.__class__.__name__}: {exc}"}

    origin_host = (urlparse(url).hostname or "").lower()
    location = result.get("location")
    redirect: dict[str, Any] = {"location": None, "host": None, "external": False}
    if location and result.get("status") in _REDIRECT_CODES:
        absolute = (
            location
            if "://" in location
            else f"{urlparse(url).scheme}://{urlparse(url).netloc}{location}"
        )
        target = urlparse(absolute)
        redirect["location"] = location
        redirect["host"] = (target.hostname or "").lower() or None
        redirect["external"] = bool(redirect["host"]) and redirect["host"] != origin_host
        if follow_redirects and not redirect["external"]:
            try:
                followed = _request_once(
                    absolute,
                    method="GET",
                    headers=headers,
                    body=None,
                    timeout=timeout,
                    capture_bytes=capture_bytes,
                )
                result["followed"] = {
                    "url": absolute,
                    "status": followed.get("status"),
                    "location": followed.get("location"),
                }
                if not result.get("body_excerpt") and followed.get("body_excerpt"):
                    result["body_excerpt"] = followed["body_excerpt"]
            except (OSError, http.client.HTTPException, ValueError) as exc:
                result["followed"] = {"url": absolute, "error": f"{exc.__class__.__name__}: {exc}"}

    result["redirect"] = redirect
    result["marker_reflected"] = bool(
        marker and isinstance(result.get("body_excerpt"), str) and marker in result["body_excerpt"]
    )
    return result


__all__ = ["HttpProbeArgs", "HttpProbeTool", "probe_http"]
