PAYLOADS: tuple[Payload, ...] = tuple(
    Payload(
        id=row[0],
        skill=row[1],
        technique=row[2],
        context=row[3],
        template=row[4],
        expected_signal=row[5],
        mode=row[6] if len(row) > 6 else "query",
        method=row[7] if len(row) > 7 else "GET",
        header=(row[8] or None) if len(row) > 8 else None,
        builder=(row[9] or None) if len(row) > 9 else None,
        note=row[10] if len(row) > 10 else "",
    )
    for row in _ENTRIES
)


def safety_report(payloads: tuple[Payload, ...] = PAYLOADS) -> SafetyReport:
    """Audit the catalogue for forbidden (destructive) content."""
    violations = []
    for payload in payloads:
        token = payload.contains_forbidden()
        if token is not None:
            violations.append((payload.id, token))
    skills = tuple(sorted({payload.skill for payload in payloads}))
    return SafetyReport(total=len(payloads), skills=skills, violations=tuple(violations))


